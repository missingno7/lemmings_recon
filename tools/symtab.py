"""Generate C offsets and validate the canonical symbol ledger."""
import re
from common import ROOT, read_json

def validate(rows):
    names=set()
    for r in rows:
        name=r['symbol_name']
        if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*',name) or name in names:
            raise ValueError('Invalid or duplicate symbol: '+name)
        names.add(name)
        for k in ('address','segment','kind','size','aliases','callers','callees','data_references','confidence','evidence','verification_status'):
            if k not in r:
                raise ValueError(f'Missing {k} in {name}')

def header():
    rows=read_json(ROOT/'metadata/symbols.json')
    validate(rows)
    lines=['/* Generated by tools/symtab.py; edit metadata/symbols.json. */',
           '#ifndef LEMMINGS_SYM_H','#define LEMMINGS_SYM_H']
    for r in rows:
        prefix='CS' if r['segment']==0 else f'SEG{r["segment"]:04X}'
        lines.append(f'#define {prefix}_{r["symbol_name"]} 0x{r["address"]:04X}u')
    return '\n'.join(lines+['#endif',''])

def generate():
    path=ROOT/'c/lemmings_sym.h'
    path.parent.mkdir(exist_ok=True)
    path.write_text(header(),encoding='utf-8')

if __name__=='__main__':
    generate()
